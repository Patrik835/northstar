def test_bybit_parser_combines_native_logs_and_deduplicates_overlaps() -> None:
    parsed = BybitStatementParser().parse(
        [
            BybitUpload("AccountChangeDetails.csv", TRANSACTION_LOG),
            BybitUpload("SpotTradeHistory.csv", SPOT_HISTORY),
            BybitUpload("SpotTradeHistory-copy.csv", SPOT_HISTORY),
        ]
    )

    assert parsed.rows_read == 5
    assert parsed.balances["BTC"].quantity == Decimal("0.01")
    assert parsed.balances["USDT"].quantity == Decimal("499.5")
    assert [item.transaction_type for item in parsed.transactions] == [
        TransactionType.DEPOSIT,
        TransactionType.BUY,
        TransactionType.FEE,
    ]
    trade = next(
        item for item in parsed.transactions if item.transaction_type is TransactionType.BUY
    )
    assert trade.ticker == "BTC"
    assert trade.currency == "USDT"
    assert trade.external_id == "trade:BTCUSDT:trade-1"


def test_bybit_parser_accepts_xlsx_sheets() -> None:
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "Spot Trade History"
    sheet.append(["Generated by Bybit"])
    sheet.append(
        [
            "Trade Time",
            "Trade ID",
            "Symbol",
            "Side",
            "Filled Qty",
            "Filled Price",
            "Filled Value",
            "Order Status",
        ]
    )
    sheet.append(
        ["2026-08-02 10:00:00", "trade-xlsx", "ETH/USDT", "Sell", 2, 3000, 6000, "Filled"]
    )
    content = io.BytesIO()
    workbook.save(content)

    parsed = BybitStatementParser().parse(
        [BybitUpload("bybit-history.xlsx", content.getvalue())]
    )

    assert parsed.transactions[0].ticker == "ETH"
    assert parsed.transactions[0].transaction_type is TransactionType.SELL
    assert parsed.transactions[0].quantity == Decimal("2")


@pytest.mark.asyncio
async def test_bybit_import_replaces_old_api_secret_values_balances_and_deduplicates() -> None:
    engine = create_engine("sqlite://")
    Base.metadata.create_all(engine)
    factory = sessionmaker(engine, expire_on_commit=False)
    cipher = CredentialCipher("MDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDA=")
    try:
        with factory() as sync_db:
            db = AsyncSessionAdapter(sync_db)
            user = User(username="bybit-file-owner", password_hash="unused")
            db.add(user)
            await db.commit()
            old_connection = BrokerConnection(
                user_id=user.id,
                broker=Broker.BYBIT,
                encrypted_credentials=cipher.encrypt(
                    {"api_key": "old-key", "secret_key": "old-secret"}
                ),
                credential_hint="••••cret",
                status=ConnectionStatus.ERROR,
            )
            db.add(old_connection)
            await db.commit()
            service = BybitStatementImportService(
                db,  # type: ignore[arg-type]
                cipher,
                prices=FixedPrices(),
                fx_rates=IdentityRates(),
            )
            uploads = [
                BybitUpload("AccountChangeDetails.csv", TRANSACTION_LOG),
                BybitUpload("SpotTradeHistory.csv", SPOT_HISTORY),
            ]

            first = await service.import_files(user.id, uploads)
            second = await service.import_files(user.id, uploads)

            assert first.positions_imported == 2
            assert first.transactions_added == 3
            assert second.transactions_added == 0
            assert second.duplicates_skipped == 3
            assert first.connection.credential_hint == "File import"
            assert cipher.decrypt(first.connection.encrypted_credentials) == {
                "source": "statement"
            }
            positions = {
                item.ticker: item
                for item in await db.scalars(select(Position).order_by(Position.ticker))
            }
            assert positions["BTC"].quantity == Decimal("0.01")
            assert positions["BTC"].current_value_eur == Decimal("550")
            assert positions["BTC"].average_price == Decimal("50000")
            assert positions["USDT"].quantity == Decimal("499.5")
            assert positions["USDT"].current_value_eur == Decimal("449.55")
            assert positions["BTC"].reported_pnl is None
            assert await db.scalar(select(func.count(Transaction.id))) == 3
    finally:
        engine.dispose()
