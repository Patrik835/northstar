class AsyncSessionAdapter:
    def __init__(self, session: Session) -> None:
        self.session = session

    def add(self, item: Any) -> None:
        self.session.add(item)

    def add_all(self, items: list[Any]) -> None:
        self.session.add_all(items)

    async def flush(self) -> None:
        self.session.flush()

    async def commit(self) -> None:
        self.session.commit()

    async def rollback(self) -> None:
        self.session.rollback()

    async def refresh(self, item: Any) -> None:
        self.session.refresh(item)

    async def execute(self, statement: Any):
        return self.session.execute(statement)

    async def scalar(self, statement: Any):
        return self.session.scalar(statement)

    async def scalars(self, statement: Any):
        return self.session.scalars(statement)

    async def get(self, model: type, item_id: Any):
        return self.session.get(model, item_id)


class FixedPrices:
    async def rates_to_eur(self, assets: set[str]) -> dict[str, Decimal]:
        available = {"BTC": Decimal("55000"), "USDT": Decimal("0.90")}
        return {asset: available[asset] for asset in assets if asset in available}


class IdentityRates:
    async def convert_to_eur(
        self, value: Decimal, currency: str, as_of: date | None = None
    ) -> Decimal:
        assert currency in {"EUR", "USD"}
        return value


